const NUMBER = "(-?[\\d.,]+)";
const TEXT = "(.*?)";

interface Pattern {
  regex: RegExp;
  kinds: ("n" | "s")[];
  spanish: string;
}

const escape = (text: string) => text.replace(/[.*+?^$()|[\]\\]/g, "\\$&");

const PATTERNS: Pattern[] = [];
const FIXED = new Map<string, string>();
for (const [english, spanish] of ENGINE_TEXT) {
  if (!/\{[ns]\}/.test(english)) {
    FIXED.set(english, spanish);
    continue;
  }
  const kinds: ("n" | "s")[] = [];
  const source = english
    .split(/(\{[ns]\})/)
    .map((piece) => {
      if (piece === "{n}" || piece === "{s}") {
        kinds.push(piece[1] as "n" | "s");
        return piece === "{n}" ? NUMBER : TEXT;
      }
      return escape(piece);
    })
    .join("");
  PATTERNS.push({ regex: new RegExp(`^${source}$`), kinds, spanish });
}
// The more fixed text a pattern has, the more surely it is the one meant.
PATTERNS.sort((a, b) => b.regex.source.replace(/\(.*?\)/g, "").length - a.regex.source.replace(/\(.*?\)/g, "").length);

/** The Spanish of an engine text, or null if it is not one of the engine's. */
export function spanishOf(text: string): string | null {
  const fixed = FIXED.get(text);
  if (fixed !== undefined) return fixed;
  const word = spanishWord(text);
  if (word !== null) return word;
  for (const pattern of PATTERNS) {
    const match = pattern.regex.exec(text);
    if (!match) continue;
    const values = match.slice(1).map((value, i) => (pattern.kinds[i] === "s" ? spanishOfPart(value) : value));
    return pattern.spanish.replace(/\{(\d+)\}/g, (_, i: string) => values[Number(i)] ?? "");
  }
  return null;
}

/** A piece inside a text: one of the engine's, a list of them, or kept as it is. */
function spanishOfPart(text: string): string {
  const whole = spanishOf(text);
  if (whole !== null) return whole;
  if (text.includes(", ")) return text.split(", ").map((part) => spanishOf(part) ?? part).join(", ");
  return text;
}
