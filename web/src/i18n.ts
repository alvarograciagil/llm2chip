const DICTIONARIES: Record<Language, Record<string, string>> = { en: {}, es: ES };

/** The text in `language`, or as written when there is no translation yet. */
export function translate(language: Language, text: string): string {
  if (language === "en") return text;
  return DICTIONARIES[language][text] ?? spanishOf(text) ?? text;
}

/** A translator for the interface's current language, redrawn when it changes. */
export function useT(): (text: string) => string {
  const language = useDesign((s) => s.language);
  return useCallback((text: string) => translate(language, text), [language]);
}

const LANGUAGE_KEY = "llm2chip.language";

/** The interface's language: English unless Spanish was chosen. The page takes it too, for
 * the number format. */
export function readLanguage(): Language {
  let language: Language = "en";
  try {
    if (localStorage.getItem(LANGUAGE_KEY) === "es") language = "es";
  } catch {
    // Without storage it stays in English.
  }
  if (typeof document !== "undefined") document.documentElement.lang = language;
  return language;
}

export function writeLanguage(language: Language) {
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    // The choice lasts until the page reloads.
  }
  document.documentElement.lang = language;
}
